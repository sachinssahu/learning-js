// while loop
let i = 0
while (i <= 10) {
    console.log(`Value of index is ${i}`);
    i += 2; // i = i + 2
}

let myArray = ["Naruto", "Sasuke", "Kurama"]
let arr = 0;

while (arr < myArray.length) {
    console.log(`Value is ${myArray[arr]}`);
    arr++;
}

// do-while loop
let score = 0

do {
    console.log(`Score is ${score}`);
    score = score + 1;
} while (score <=10);